class TestWorldBasis:
    def test_z_up_maps_onto_godot_up(self):
        basis = frame_axes.world_basis_for(up_axis=2, width_axis=1, up_sign=1)
        # frame +z (up) must land on Godot +y
        assert np.allclose(basis @ np.array([0.0, 0.0, 1.0]), [0.0, 1.0, 0.0])

    def test_negative_up_sign_flips_the_vertical(self):
        basis = frame_axes.world_basis_for(up_axis=2, width_axis=1, up_sign=-1)
        assert np.allclose(basis @ np.array([0.0, 0.0, 1.0]), [0.0, -1.0, 0.0])

    @pytest.mark.parametrize("up_axis", [0, 1, 2])
    @pytest.mark.parametrize("width_axis", [0, 1, 2])
    def test_always_a_proper_rotation(self, up_axis, width_axis):
        if up_axis == width_axis:
            with pytest.raises(ValueError):
                frame_axes.world_basis_for(up_axis=up_axis, width_axis=width_axis)
            return
        basis = frame_axes.world_basis_for(up_axis=up_axis, width_axis=width_axis)
        assert float(np.linalg.det(basis)) == pytest.approx(1.0)
        assert np.allclose(basis @ basis.T, np.eye(3))

    def test_every_frame_up_axis_lands_on_godot_up(self):
        for up_axis in (0, 1, 2):
            for width_axis in (0, 1, 2):
                if up_axis == width_axis:
                    continue
                basis = frame_axes.world_basis_for(up_axis, width_axis, 1)
                axis = np.eye(3)[up_axis]
                assert np.allclose(basis @ axis, [0.0, 1.0, 0.0])

    def test_rejects_up_sign_zero(self):
        with pytest.raises(ValueError):
            frame_axes.world_basis_for(up_axis=2, width_axis=1, up_sign=0)

    def test_remaining_axis_is_the_spare_one(self):
        assert frame_axes.remaining_axis(2, 1) == 0
        assert frame_axes.remaining_axis(0, 2) == 1

    def test_axis_index_round_trips(self):
        for index, name in enumerate(frame_axes.AXIS_NAMES):
            assert frame_axes.axis_index(name) == index
        with pytest.raises(ValueError):
            frame_axes.axis_index("w")


