class TestScaleReference:
    def test_tolerance_grows_with_measured_spread(self):
        # 1% spread stays under the 10% floor; 10% spread sits on it; 30% is above.
        tight = ScaleReference("chosen", "h", 1.0, 0.01, 10, 2.4, "")
        floored = ScaleReference("chosen", "h", 1.0, 0.05, 10, 2.4, "")
        loose = ScaleReference("chosen", "h", 1.0, 0.30, 10, 2.4, "")
        assert floored.tolerance_metres == pytest.approx(tight.tolerance_metres)
        assert loose.tolerance_metres > floored.tolerance_metres

    def test_tolerance_tracks_the_raw_measurement(self):
        # The same fractional spread in a smaller measurement gives a smaller
        # tolerance, which is what makes the value meaningful rather than arbitrary.
        small = ScaleReference("chosen", "h", 0.5, 0.05, 10, 2.4, "")
        large = ScaleReference("chosen", "h", 2.0, 0.20, 10, 2.4, "")
        assert small.tolerance_metres == pytest.approx(large.tolerance_metres)

    def test_tolerance_is_floored_at_ten_percent(self):
        # A suspiciously perfect reconstruction must not demand an impossible
        # tolerance.
        reference = ScaleReference("chosen", "h", 1.0, 0.0, 10, 2.4, "")
        assert reference.tolerance_metres == pytest.approx(0.24)

    def test_rejects_zero_raw_units(self):
        # Zero raw units means a division by zero in the tolerance formula; the
        # property is read to force it rather than merely constructing the record.
        reference = ScaleReference("chosen", "h", 0.0, 0.01, 10, 2.4, "")
        with pytest.raises(ContractError):
            _ = reference.tolerance_metres


