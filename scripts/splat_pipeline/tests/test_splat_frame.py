#!/usr/bin/env python3
"""Tests for the alignment contract: PLY reading, frame maths, manifest validation.

These cover the pure logic, so the expensive measurement run does not have to be
repeated to check that the contract still holds its own invariants. The specific
bugs these guard against are the ones that shipped:

* the up axis read from the wrong basis column, which passed because the wrong
  column happened to look plausible
* a mirrored (det < 0) basis, which parses and renders
* the centroid translation applied twice, which shifts the room silently
* trusting the normal's *sign* to pick floor vs ceiling, which finds the same
  sheet twice and reports a zero-thickness room

Run with: python3 -m pytest scripts/splat_pipeline/tests/test_splat_frame.py -v
"""

