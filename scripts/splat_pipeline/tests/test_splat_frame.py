PROPERTIES = [
    "x", "y", "z",
    "scale_0", "scale_1", "scale_2",
    "opacity",
    "rot_0", "rot_1", "rot_2", "rot_3",
]


def write_ply(path: Path, rows: list[dict]) -> None:
    """Write a minimal binary_little_endian 3DGS PLY with the given rows."""
    header = (
        "ply\n"
        "format binary_little_endian 1.0\n"
        "comment Generated by test\n"
        "comment Vertical Axis: z\n"
        f"element vertex {len(rows)}\n"
        + "".join(f"property float {name}\n" for name in PROPERTIES)
        + "end_header\n"
    )
    body = b"".join(
        struct.pack("<%df" % len(PROPERTIES), *[float(row.get(name, 0.0)) for name in PROPERTIES])
        for row in rows
    )
    path.write_bytes(header.encode("ascii") + body)


def make_row(x=0.0, y=0.0, z=0.0, opacity=10.0):
    return {"x": x, "y": y, "z": z, "opacity": opacity, "rot_0": 1.0, "scale_0": -6.0}


class TestSplatPly:
    def test_reads_positions_and_count(self, tmp_path):
        ply = tmp_path / "a.ply"
        write_ply(ply, [make_row(1.0, 2.0, 3.0), make_row(-1.0, -2.0, -3.0)])
        header = splat_ply.parse_header(ply)
        assert header.vertex_count == 2
        assert header.properties == tuple(PROPERTIES)
        assert np.allclose(splat_ply.read_positions(ply), [[1, 2, 3], [-1, -2, -3]])

    def test_alphas_are_sigmoid_of_opacity(self, tmp_path):
        ply = tmp_path / "b.ply"
        write_ply(ply, [make_row(opacity=0.0), make_row(opacity=1000.0)])
        alphas = splat_ply.read_alphas(ply)
        assert alphas[0] == pytest.approx(0.5, abs=1e-6)
        assert alphas[1] == pytest.approx(1.0, abs=1e-6)

    def test_header_comments_are_exposed_as_provenance(self, tmp_path):
        ply = tmp_path / "c.ply"
        write_ply(ply, [make_row()])
        comments = splat_ply.header_comments(ply)
        assert comments["generated"] == "by test"
        # The exporter's claim about the frame is recorded, not trusted.
        assert comments["vertical"] == "Axis: z"

    def test_rejects_non_binary_ply(self, tmp_path):
        ply = tmp_path / "ascii.ply"
        ply.write_text("ply\nformat ascii 1.0\nend_header\n")
        with pytest.raises(splat_ply.PlyFormatError):
            splat_ply.parse_header(ply)

    def test_rejects_missing_position_properties(self, tmp_path):
        ply = tmp_path / "bad.ply"
        ply.write_bytes(
            b"ply\nformat binary_little_endian 1.0\nelement vertex 1\n"
            b"property float u\nproperty float v\nend_header\n" + b"\x00" * 8
        )
        with pytest.raises(splat_ply.PlyFormatError):
            splat_ply.parse_header(ply)


