def write_colmap_images(path: Path, records: list[dict]) -> None:
    """Write a COLMAP images.bin from simple records."""
    with path.open("wb") as handle:
        handle.write(struct.pack("<Q", len(records)))
        for record in records:
            handle.write(struct.pack("<i", record["image_id"]))
            handle.write(struct.pack("<4d", *record["qvec"]))
            handle.write(struct.pack("<3d", *record["tvec"]))
            handle.write(struct.pack("<i", record["camera_id"]))
            handle.write(record["name"].encode("ascii") + b"\x00")
            handle.write(struct.pack("<Q", 0))


class TestColmapModel:
    def test_camera_centre_from_quaternion(self, tmp_path):
        write_colmap_images(tmp_path / "images.bin", [
            {"image_id": 1, "qvec": (1.0, 0.0, 0.0, 0.0), "tvec": (0.0, 0.0, 5.0),
             "camera_id": 1, "name": "a.jpg"},
        ])
        images = colmap_model.read_images(tmp_path)
        # identity rotation, t = +5 z -> camera centre at -5 z
        assert np.allclose(images[0].camera_center, [0.0, 0.0, -5.0])

    def test_view_and_up_directions_use_colmap_convention(self, tmp_path):
        write_colmap_images(tmp_path / "images.bin", [
            {"image_id": 1, "qvec": (1.0, 0.0, 0.0, 0.0), "tvec": (0.0, 0.0, 0.0),
             "camera_id": 1, "name": "a.jpg"},
        ])
        image = colmap_model.read_images(tmp_path)[0]
        # COLMAP: +Z forward, +Y down, +X right
        assert np.allclose(image.view_direction, [0.0, 0.0, 1.0])
        assert np.allclose(image.up_direction, [0.0, -1.0, 0.0])
        assert np.allclose(image.right_direction, [1.0, 0.0, 0.0])

    def test_up_direction_uses_majority_not_mean(self, tmp_path):
        """One flipped pose must not invert the scene's up axis."""
        records = [{"image_id": i, "qvec": (1.0, 0.0, 0.0, 0.0), "tvec": (0.0, 0.0, 0.0),
                    "camera_id": 1, "name": f"{i}.jpg"} for i in range(9)]
        # Flip one camera by 180 degrees about x: q = (0, 1, 0, 0)
        records[0]["qvec"] = (0.0, 1.0, 0.0, 0.0)
        write_colmap_images(tmp_path / "images.bin", records)
        images = colmap_model.read_images(tmp_path)
        up = colmap_model.dominant_up_direction(images)
        assert up[1] < 0.0

    def test_principal_axis_index(self, tmp_path):
        write_colmap_images(tmp_path / "images.bin", [
            {"image_id": 1, "qvec": (1.0, 0.0, 0.0, 0.0), "tvec": (0.0, 0.0, 0.0),
             "camera_id": 1, "name": "a.jpg"},
        ])
        up = colmap_model.dominant_up_direction(colmap_model.read_images(tmp_path))
        index, magnitude = colmap_model.dominant_up_axis_index(up)
        assert index == 1
        assert magnitude < 0.0

    def test_rejects_degenerate_quaternion(self, tmp_path):
        write_colmap_images(tmp_path / "images.bin", [
            {"image_id": 1, "qvec": (0.0, 0.0, 0.0, 0.0), "tvec": (0.0, 0.0, 0.0),
             "camera_id": 1, "name": "a.jpg"},
        ])
