def test_sampling_cost_does_not_track_clip_length(clips):
    """A 900-frame clip must not cost 9x a 96-frame one to sample.

    The budget is on selected frames and analysis pixels, not on the length of
    the input, so the two clips are compared with the same target. Both are
    sampled by a stream that visits every frame, so a strict bound does not hold
    -- what must hold is that the ratio stays far below the 9.4x length ratio,
    because the retained set is what the budget bounds.
    """
    short = gate(clips, "accepted_walkthrough")
    long_report = gate(clips, LONG_CLIP)
    length_ratio = probe_video(clips[LONG_CLIP]).frame_count / probe_video(
        clips["accepted_walkthrough"]
    ).frame_count
    time_ratio = long_report["seconds"] / max(short["seconds"], 1e-9)
    assert time_ratio < length_ratio / 2, (
        f"sampling the long clip took {time_ratio:.1f}x the short clip's time for a "
        f"{length_ratio:.1f}x longer input -- the cost is not bounded"
    )


def test_the_long_clip_keeps_only_a_bounded_fraction_of_its_frames(clips):
    report = gate(clips, LONG_CLIP)
    retained = report["scan"]["decode"]["candidates"]["retained"]
    total = report["scan"]["decode"]["candidates"]["clip_frames"]
    assert retained <= SamplingBudget().max_candidates
    assert retained < total / 2


def test_the_long_clip_selection_lands_inside_the_frame_hypothesis(clips):
    report = gate(clips, LONG_CLIP)
    selected = report["selection"]["selected_count"]
    assert 100 <= selected <= 200


def test_every_dropped_frame_is_accounted_for(clips):
    """Excluded plus selected must equal what was scored -- no silent losses."""
    for name in ("accepted_walkthrough", "cut_sequence", "moving_content"):
        report = gate(clips, name)
        scored = len(report["scan"]["candidates"])
        selected = report["selection"]["selected_count"]
        excluded = len(report["selection"]["exclusions"])
        assert selected + excluded == scored


@pytest.mark.parametrize("motion", [2.0, 3.0, 5.0])
def test_the_candidate_cap_widens_the_stride_for_a_longer_clip(clips, motion):
    """The stride is the wider of two constraints; on a long clip the cap binds.

    The motion constraint alone would keep the stride fixed, which is what bounds
    the *quality* of each sample. What has to grow with clip length is the
    stride, so the number of candidates stays inside ``max_candidates`` --
    otherwise a long clip scores 900 frames and the budget bounds nothing.
    """
    budget = SamplingBudget()
    width = analysis_size(probe_video(clips[LONG_CLIP]), budget.analysis_max_pixels).width
    long_frames = probe_video(clips[LONG_CLIP]).frame_count
    long_stride = candidate_stride_for(long_frames, motion, width, budget)
    short_stride = candidate_stride_for(96, motion, width, budget)
    assert long_stride > short_stride
    assert -(-long_frames // long_stride) <= budget.max_candidates


def test_the_stride_for_a_long_clip_is_measured_from_that_clip_not_a_guess(clips):
    """Asserting the cap bound, so the bound is not the only thing under test."""
    budget = SamplingBudget()
    scan = scan_capture(probe_video(clips[LONG_CLIP]), budget)
    expected = candidate_stride_for(scan.metadata.frame_count, scan.motion_px_per_frame, scan.size.width, budget)
    assert scan.stride == expected
    assert len(scan.candidates) <= budget.max_candidates


