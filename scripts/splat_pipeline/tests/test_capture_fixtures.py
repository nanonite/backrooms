def test_the_written_frame_is_the_frame_the_gate_selected(clips, tmp_path):
    """The seek convention has to land on the chosen index, not the one after it.

    ffmpeg's accurate ``-ss`` returns the first frame at or after the target, so
    a half-frame offset would silently write the *next* frame -- and on the last
    frame of a clip it writes nothing at all.
    """
    video = clips["accepted_walkthrough"]
    metadata = probe_video(video)
    size = analysis_size(metadata, 64 * 36)
    streamed = stream_candidates(video, size, stride=1, clip_frames=metadata.frame_count)
    by_index = dict(zip(streamed.indices, streamed.frames))

    for index in (0, 1, 40, 94, 95):
        sought = seek_candidates(video, size, [index], metadata.fps)
        assert sought.indices == (index,), f"seek reported frame {sought.indices} for {index}"
        difference = abs(sought.frames[0].astype(int) - by_index[index].astype(int)).mean()
        assert difference == 0, f"seek for frame {index} differs by {difference:.2f} grey levels"


def test_frame_timestamp_is_the_frames_own_presentation_time():
    assert frame_timestamp(24, 24.0) == pytest.approx(1.0)
    assert frame_timestamp(0, 24.0) == 0.0


def test_frame_timestamp_falls_back_when_the_rate_is_unknown():
    assert frame_timestamp(25, 0.0) == pytest.approx(25 / 25.0)


def test_seeking_the_last_frame_returns_it_rather_than_nothing(clips):
    video = clips["accepted_walkthrough"]
    metadata = probe_video(video)
    size = analysis_size(metadata, 64 * 36)
    last = metadata.frame_count - 1
    sought = seek_candidates(video, size, [last], metadata.fps)
    assert sought.frames, "the final frame of a clip must be reachable by seek"


