#: Clip length the long-clip comparison uses. Long enough to be visibly longer
#: than the budget and still fast to decode twice.
LONG_CLIP = "long_walkthrough"


@pytest.fixture(scope="session")
def clips(tmp_path_factory) -> dict[str, Path]:
    """Build every fixture once per session into a temporary directory."""
    output = tmp_path_factory.mktemp("clips")
    try:
        built = build_all(output)
    except FixtureError as exc:
        pytest.skip(f"could not build the capture fixtures: {exc}")
    return {fixture.name: path for fixture, path in built}


def budget_for(name: str, **overrides) -> SamplingBudget:
    """A budget sized for one fixture, with the overrides applied."""
    defaults = {
        "target_frames": 150,
        "max_candidates": 240,
        "decode_mode": "stream",
    }
    defaults.update(overrides)
    return SamplingBudget(**defaults)


def gate(clips: dict[str, Path], name: str, **overrides) -> dict:
    """Run the whole gate over one fixture and return its report."""
    return capture_gate.run_gate(clips[name], budget_for(name, **overrides), clips[name].parent)


