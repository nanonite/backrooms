#!/usr/bin/env python3
"""End-to-end tests for the capture gate against repeatable synthetic clips.

This is where the accepted/rejected fixture pairs earn their keep: each clip has
a known property, so the verdict is asserted against a property rather than
against a recording of what the code used to print. The clips are generated by
``fixtures/make_capture_fixtures.py``, so the whole file is reproducible on any
machine with ffmpeg and numpy and no shipped footage.

Two things are checked that a unit test cannot be:

* the fixtures really do have the properties they claim (a "moving content"
  fixture whose moving object covers 0.1% of the frame would silently stop
  testing anything);
* the bounded-work promise holds -- the long clip must not cost more than the
  short one by an amount that tracks its length.

Needs ffmpeg and ffprobe. Skipped, not failed, when they are absent.

Run from ``scripts/splat_pipeline``:
    python3 -m pytest tests/test_capture_fixtures.py -q
"""

