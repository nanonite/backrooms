def test_extraction_writes_exactly_the_selected_frames_at_source_resolution(clips, tmp_path):
    report = gate(clips, "accepted_walkthrough")
    destination = tmp_path / "images"
    extraction = sample_frames.extract_selection(report, clips["accepted_walkthrough"], destination)
    assert extraction.frames_written == len(report["selection"]["selected"])
    written = sorted(path.name for path in destination.glob("frame_*.jpg"))
    assert len(written) == extraction.frames_written
    # The analysis frames are downscaled; the written frames must not be.
    assert extraction.analysis_resolution == extraction.source_resolution


